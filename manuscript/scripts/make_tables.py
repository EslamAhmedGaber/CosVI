def write(name, body):
    # every tabular is capped at the line width (adjustbox max width: scales down only, in the layout that needs it)
    i = body.find(r"\begin{tabular}")
    j = body.find(r"\end{tabular}")
    if i >= 0 and j > i:
        j += len(r"\end{tabular}")
        body = body[:i] + r"\begin{adjustbox}{max width=\linewidth}" + "\n" + body[i:j] + "\n" + r"\end{adjustbox}" + body[j:]
    with open(os.path.join(OUT, name), "w", encoding="utf-8") as fh:
        fh.write("% Generated by scripts/make_tables.py. Do not edit by hand.\n" + body)


def ierr(s, ref):
    return 100 * np.abs(np.asarray(s) - np.asarray(ref)).sum() / np.asarray(ref).sum()


def n3(rep, H, th):
    cs = [json.load(open(f)) for f in sorted(glob.glob(os.path.join(S.RES, "n3", f"n3_{rep}_H{H:.2f}_theta{th:.1f}_seed*.json")))]
    e = np.array([100 * c["metrics"]["exact_true"]["std_relerr_integrated"] for c in cs])
    return e.mean(), e.min(), e.max()



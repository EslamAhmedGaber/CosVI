        v = []
        for s in range(5):
            r = json.load(open(os.path.join(S.RES, "x8", f"x8c_seed{s}_H{float(H):.2f}.json")))
            e = dict(zip(r["arms"], r["drift_rmse_occupation"]))
            v.append(e[second] - e[first])
        return float(np.mean(v)), float(np.std(v, ddof=1) / np.sqrt(len(v)))

